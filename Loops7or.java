import java.util.Scanner;

public class Loops7or {
  public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();

        for(int i = 1; i <= n; i++) {

            if (i % 2 != 0) {     //here we used if (i % 2 != 0) for print odd num 
                System.out.println(i);

            }
            
            }
            
        }
  
}
